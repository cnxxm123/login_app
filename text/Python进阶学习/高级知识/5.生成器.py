"""
【生成器 Generator —— Python 高级特性】

一、核心概念
    只要函数体内出现了关键字 yield，这个函数就不再是普通函数，而是"生成器函数"。
    调用生成器函数时，函数体【不会立即执行】，而是返回一个"生成器对象"(generator)。
    生成器对象是迭代器（Iterable + Iterator），可以交给 for 循环、next() 使用。

二、工作原理（惰性求值 / 暂停-恢复）
    1. 第一次调用 next(g)（或进入 for 循环）时，函数开始执行，一直运行到
       第一个 yield 处：yield 后面的值会被"产出"给调用方，然后函数在此【暂停】。
    2. 下次再调用 next(g)（或 for 继续）时，从上次暂停的地方【继续】执行，
       直到遇到下一个 yield 再暂停。
    3. 函数执行完（或遇到 return）后，会抛出 StopIteration 异常，for 循环
       捕获它后就正常结束（所以 for 循环看不到 StopIteration）。

三、next() 与 for 循环的区别
    - next(g)：一次取一个值；取完所有值后再 next 会抛出 StopIteration。
    - for x in g：本质是不断调用 next() 直到捕获 StopIteration 自动结束，
      因此更安全、更常用，不需要手动处理异常。

四、为什么要用生成器（省内存）
    普通列表 [i**2 for i in range(10**9)] 会一次性在内存里生成 10 亿个元素，
    内存直接爆掉。而生成器是"边算边给"，每次只产生一个值，几乎不占内存。
    典型应用：读大文件时逐行 yield、无限序列（斐波那契）、流水线处理。

五、易错点
    1. 调用生成器函数不会执行任何代码，别忘记必须迭代它（for/next）才会真正执行。
    2. 生成器只能用一次：迭代完就"耗尽"了，想要再用必须重新调用函数创建。
    3. 生成器不是函数结果：return 的值不会作为迭代值输出（它会随 StopIteration 走）。
"""


# =====================================================================
# 示例一：带 yield 的函数是生成器，调用后返回生成器对象
# =====================================================================
def main():  # 函数变成了生成器，是一个可迭代对象
    print('set1')
    yield 1          # 暂停：把 1 交给调用方，函数在这里停住
    print('set2')
    yield 2          # 再次暂停：把 2 交给调用方
    print('set3')
    yield 3          # 第三次暂停：把 3 交给调用方


def squares(num: int):
    """生成 1~num 的平方数（一次只产生一个，省内存）"""
    for i in range(1, num + 1):
        yield i ** 2   # 每循环一次，就暂停并产生一个平方值


if __name__ == '__main__':
    print('===== 演示：调用生成器函数不会立即执行 =====')
    g = main()                        # 注意：这里还没有打印 set1！
    print('调用 main() 返回的对象类型:', type(g))  # <class 'generator'>
    print('调用 main() 后函数体并未执行（上方没有 set1 输出）')

    print('\n===== 用 next() 手动逐个取值（观察暂停/继续）=====')
    g2 = main()                       # 重新创建一个生成器
    print('第一次 next:', next(g2))    # 执行到第一个 yield -> 打印 set1，返回 1
    print('第二次 next:', next(g2))    # 从暂停处继续 -> 打印 set2，返回 2
    print('第三次 next:', next(g2))    # 从暂停处继续 -> 打印 set3，返回 3
    try:
        next(g2)                      # 已经没有 yield 了，函数结束 -> 抛 StopIteration
    except StopIteration:
        print('第四次 next: 抛出了 StopIteration（生成器已耗尽）')

    print('\n===== 用 for 循环迭代（自动处理 StopIteration）=====')
    for res in main():                # for 内部自动调用 next()，结束后自动停止
        print(res)

    print('\n===== 生成器函数 squares() 的惰性求值 =====')
    for squ in squares(10):           # 产生 1、4、9、...、100
        print(squ)


# =====================================================================
# 补充示例一：生成器表达式（省内存）—— 对比列表推导式
# =====================================================================
print('\n===== 补充示例一：生成器表达式（省内存）=====')
# 列表推导式：一次性生成完整列表，占用大量内存
list_result = [i * 2 for i in range(5)]
print('列表推导式:', list_result, type(list_result))

# 生成器表达式：圆括号包裹，得到一个生成器，边用边算
gen_result = (i * 2 for i in range(5))
print('生成器表达式:', gen_result, type(gen_result))
print('逐个取出生成器的值:', list(gen_result))   # list() 可以一次性把生成器转成列表


# =====================================================================
# 补充示例二：无限序列 —— 生成器最经典的用法
# 斐波那契数列，理论上可以无穷生成下去而不占内存
# =====================================================================
def fibonacci():
    """无限生成斐波那契数列（0, 1, 1, 2, 3, 5, 8, ...）"""
    a, b = 0, 1
    while True:          # 无限循环，靠调用方决定取多少
        yield a          # 每次暂停返回当前的 a
        a, b = b, a + b  # 计算下一个数（在暂停恢复后继续执行到这里）


print('\n===== 补充示例二：无限斐波那契数列 =====')
fib = fibonacci()
for _ in range(10):      # 只取前 10 个，随时可以停止
    print(next(fib), end=' ')
print()                  # 换行
