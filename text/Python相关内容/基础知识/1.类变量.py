"""
知识点：类变量（类属性）与实例变量（实例属性）
=================================================

【核心概念】
- 类变量（类属性）：直接在类体内、方法之外定义的变量，属于"类"本身，
  所有实例对象和类本身都能共享访问它。
- 实例变量（实例属性）：在 __init__ 里通过 self.xxx = ... 绑定的变量，
  属于"单个实例"，每个实例各有一份，互不影响。

【工作原理】
- Python 的类和对象本质上都是"字典"（命名空间）。
- 类变量存放在 类.__dict__ 中；实例变量存放在 实例.__dict__ 中。
- 属性查找顺序（重点）：
    1. 先查实例的 __dict__（实例自己的属性，如 self.a）
    2. 再查类的 __dict__（类变量、方法等）
    3. 最后查父类（基类）的 __dict__，依次向上
  也就是说：实例变量可以"遮蔽"(shadow) 同名类变量。

【使用场景】
- 用类变量保存所有实例共享的数据，例如：计数器、默认配置、常量、所有实例数量等。
- 用实例变量保存每个对象各自独立的数据。

【注意事项 / 易错点】
1. 给实例赋值同名属性时，会创建一个"实例变量"遮蔽掉"类变量"，
   但这不会修改类变量本身（除非直接操作类）。
2. 通过"实例.属性 = 值"只能创建/修改实例变量，永远改不到类变量；
   只有通过"类.属性 = 值"才能修改类变量。
3. 修改类变量，所有实例的访问结果都会随之改变（因为它们共享类变量）。
4. 通过 __dict__ 可以清楚地区分：类的命名空间 vs 实例的命名空间。
5. getattr / setattr / delattr 是"反射式"地操作属性，
   适合属性名是"变量（动态字符串）"的场合，比写死的 对象.属性 更灵活。
"""


# ============================================================
# 一、基础示例：类变量 vs 实例变量
# ============================================================

class Student:
    cou = 1      # 类变量：所有实例共享
    a = 2        # 类变量：所有实例共享

    def __init__(self):
        # self.a = 1 会把实例自己的 a 放在 实例.__dict__ 里，
        # 从而"遮蔽"类里同名的类变量 a = 2。
        self.a = 1  # 实例变量：只属于这个对象

    def say(self):
        # 方法本身也是一个属性（存放在类的 __dict__ 中），
        # 只不过它的值是一个"函数"。
        print(878)


print(Student.__name__)
# __name__ 是类的内置属性，返回类的名字（字符串），
# 例如这里会输出 'Student'。
print('----------------------------------------')


# ============================================================
# 二、getattr / setattr / delattr：动态操作属性
# ============================================================

# getattr(对象, '属性名', 默认值)：动态获取属性。
# 如果属性不存在且没有给默认值，会抛 AttributeError；
# 给了默认值，则属性不存在时返回默认值。
print(getattr(Student, 'unknown', 10))
# 上面在 Student 类里查找 'unknown'，类里没有这个属性，
# 于是返回我们提供的默认值 10（而不是报错）。

# setattr(对象, '属性名', 值)：动态设置属性，等价于 对象.属性名 = 值。
setattr(Student, 'school', '北大')   # 等价于 Student.school = '北大'
print(Student.school)                # 访问动态设置的类变量

# delattr(对象, '属性名')：动态删除属性，等价于 del 对象.属性名。
delattr(Student, 'school')           # 把刚才设置的 school 删掉
# print(Student.school)              # 再访问会抛 AttributeError（已被删除）

# 小提示：getattr/setattr/delattr 非常适合"属性名来自运行时变量"的场景，
# 例如根据用户输入动态决定访问哪个字段。
print('----------------------------------------')


# ============================================================
# 三、实例属性 / 类变量的动态添加
# ============================================================

student = Student()          # 创建一个实例
print(student.cou)           # 实例访问类变量 cou，输出 1
# 查找过程：实例.__dict__ 里没有 cou → 类.__dict__ 里有 cou=1 → 返回 1

student.ads = 12             # 直接给"实例"动态添加属性 ads
print(student.ads)           # 输出 12，这个属性只存在于该实例上

Student.age = 18             # 通过"类"动态添加类变量 age
print(Student.age)           # 类可以直接访问，输出 18
print(student.age)           # 实例也能访问（共享类变量），输出 18
print('----------------------------------------')


# ============================================================
# 四、__dict__：看清属性的存放位置
# ============================================================

print(Student.__dict__)
# 对于"类"来说，__dict__ 是一个 dict（映射代理对象），
# 里面存放了类的所有属性、方法、类变量，以及 __module__、__name__ 等
# 由解释器自动生成的内置属性。
# 注意：Student.__dict__ 里能看到 cou、a、say，但看不到实例的 ads。

print(student.__dict__)
# 对于"实例"来说，__dict__ 是一个普通的字典，
# 里面只存放该实例自己的实例变量（self.a = 1，以及动态加的 ads）。
# 注意：实例的 __dict__ 里【没有】cou 和 say，因为它们属于类。

# 差异小结：
#   Student.__dict__  -> 类的命名空间（类变量、方法、内置属性）
#   student.__dict__  -> 实例的命名空间（仅实例变量，不含类变量和方法）
print('----------------------------------------')


# ============================================================
# 五、实例变量遮蔽类变量（属性查找顺序演示）
# ============================================================

print(student.a)   # 输出 1
# 查找顺序：先查实例.__dict__，里面有 self.a = 1，直接返回 1，
# 所以即使类里还有类变量 a = 2，也不会被用到（被"遮蔽"了）。

print(Student.a)   # 输出 2
# 直接访问类，得到的是类变量本身的值 2，和实例互不影响。
