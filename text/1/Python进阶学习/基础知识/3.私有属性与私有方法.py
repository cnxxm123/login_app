"""
知识点：私有属性与私有方法
=============================

【核心概念】
- Python 没有像 Java/C++ 那样真正的"私有"机制，
  它靠【命名约定 + 名称改写】来"约定"哪些成员是私有的。
- 单下划线前缀 _：只是"约定"（convention），表示"这是内部/私有的，
  不要从外部直接访问"。它【不会】阻止任何访问，仅仅是给其他开发者看的信号。
- 双下划线前缀 __（且不以 __ 结尾）：会触发"名称改写"(name mangling)。
  解释器会在类内部把 __attr 自动改写成 _ClassName__attr，
  从而实现"伪私有"，外部直接用 __attr 访问会报错。

【工作原理】
- 名称改写发生在"编译期"：凡是写在类体内部的 __attr 都会被替换成 _ClassName__attr。
- 例如 class Student 里的 self.__age 实际存的是 self._Student__age。
- 这就是为什么外部仍然可以通过 st1._Student__age 强行访问到它。

【使用场景】
- 用 _ 前缀保护"内部实现细节"，提示调用者不要乱动。
- 用 __ 前缀防止子类/外部不小心覆盖或误用内部成员（名称改写同时作用于子类，
  子类里定义的同名 __attr 会被改写成 _子类名__attr，从而避免与父类冲突）。
- 真正的封装/校验还是要靠 @property（见 6、7、8 号文件）。

【注意事项 / 易错点】
1. 单下划线 _ 只是"君子协定"，外部依然可以随意访问，不报错。
2. 双下划线 __ 触发名称改写后，外部用 obj.__attr 会直接报 AttributeError，
   但用 obj._ClassName__attr 依然能访问，所以它"防君子不防小人"。
3. 名称改写对"类体内部"才生效；在类外面写 __xxx 不会被改写。
4. 不要定义以双下划线开头【且以双下划线结尾】的名字（如 __init__），
   那是 Python 的特殊方法（魔法方法），不是私有成员。
5. 通过"点号访问"会被改写，但用 getattr(obj, '__attr') 同样会被改写；
   只有明确写出 _ClassName__attr 才能拿到。
"""


class Student:
    def __init__(self, name: str, age: int):
        # 单下划线 _name：只是"约定"为私有，外部依然可以直接访问 st1._name。
        self._name = name
        # 双下划线 __age：触发名称改写，实际存储的名字是 _Student__age。
        # 外部写 st1.__age 会报错，但写 st1._Student__age 能访问到。
        self.__age = age

    # 单下划线 _say_hello：约定为"私有方法"，外部仍可调用，不报错。
    def _say_hello(self):  # 在前面加 _ 或者 __ 表示私有方法
        print(f'hello{self._name}')

    # 双下划线 __say_age：触发名称改写，方法名被改为 _Student__say_age。
    def __say_age(self):  # 在前面加 _ 或者 __ 表示私有方法
        print(f'{self.__age}岁')


st1 = Student('张三', 18)

# ---- 单下划线：约定私有，但可以访问 ----
print(st1._name)      # 输出 '张三'，因为 _ 只是约定，不真正拦截访问
st1._say_hello()      # 可以正常调用，输出 hello张三
print('----------------------------------------')

# ---- 双下划线：名称改写，直接访问会报错 ----
# print(st1.__age)        # 会抛 AttributeError：'Student' object has no attribute '__age'
# st1.__say_age()         # 同样会抛 AttributeError

# ---- 但通过"改写后的名字"可以访问 ----
print(st1._Student__age)      # 输出 18，因为 self.__age 实际存的是 _Student__age
st1._Student__say_age()       # 正常调用，输出 18岁
print('----------------------------------------')


# ============================================================
# 补充示例 1：验证名称改写真的发生了（查看命名空间）
# ============================================================

# 打印实例的命名空间，可以看到实际存储的属性名是 _Student__age，
# 而 __age 这个名字并不存在。
print(st1.__dict__)
# 输出类似：{'_name': '张三', '_Student__age': 18}
# 注意：没有 __age，只有被改写后的 _Student__age。
print('----------------------------------------')


# ============================================================
# 补充示例 2：名称改写在"子类"中如何避免冲突
# ============================================================

class A:
    def __init__(self):
        self.__x = 1          # 实际存为 self._A__x

    def get_x(self):
        return self.__x       # 在 A 内部访问的就是 _A__x


class B(A):
    def __init__(self):
        super().__init__()
        self.__x = 2          # 实际存为 self._B__x，与父类的 _A__x 不冲突


b = B()
print(b._A__x)                # 输出 1（父类的内部数据，被保护起来）
print(b._B__x)                # 输出 2（子类自己的内部数据）
print(b.get_x())              # 输出 1（父类方法访问的是父类的 _A__x）
# 小结：双下划线让父类/子类的内部数据彼此隔离，防止被子类意外覆盖。
