"""
【闭包 Closure —— Python 高级特性】

一、闭包的定义
    闭包 = 内层函数 + 它引用的外层函数变量（这些变量叫"自由变量"）。
    当外层函数【返回内层函数】，并且内层函数用到了外层函数的局部变量时，
    就形成了一个闭包。

二、关键机制：外层函数结束后，变量为什么还在？
    普通局部变量在外层函数执行完就会销毁。但内层函数引用了它，Python 会把这
    个变量"打包"进内层函数的 __closure__ 属性（一个 cell 元组）里保存下来。
    因此即使外层函数已经返回，内层函数依然能访问到那份变量，且每次调用都能
    保持上一次的状态（也就是"记忆能力"）。

三、闭包的用途
    1. 延迟计算：先拿到函数，需要时才真正执行。
    2. 计数器 / 有状态函数：靠闭包保存并更新状态（配合 nonlocal）。
    3. 装饰器的底层原理：装饰器本质上就是闭包——外层函数接收函数，
       内层函数捕获它并做包装。
    4. 数据隐藏：把"私有状态"封装在闭包里，外部无法直接访问。

四、闭包陷阱（重点易错点）
    在循环中创建闭包时，如果内层函数引用循环变量，多个闭包会【共享同一个变量】
    而不是各自保存一份副本。因为循环变量是一个可变的 cell，循环结束后它停留在
    最后一个值，所有闭包读到的都是这个最终值。
    解决办法：用默认参数绑定当前值（lambda i=i: ...），或把值作为参数传入。

五、观察方法
    fn.__closure__ 是一个元组，每个元素是一个 cell；
    cell.cell_contents 可以查看闭包保存的变量当前值。
"""


def greeting():
    msg = 'fsdfdf'       # 外层函数 greeting 的局部变量 msg
    def inner():         # 内部函数：引用了外层变量 msg
        print(msg)       # 读取外层变量 msg（这就是"自由变量"）

    msg = '123'          # 外层函数再次给 msg 赋值 -> 闭包捕获的是"最终值 123"

    # 当函数执行完后 msg 会消失，但 inner 需要用到 msg

    # 返回 inner：因为 inner 引用了 msg，msg 会被保存进 inner.__closure__
    return inner         # msg 被保存一份在 __closure__（元组）中，这就是闭包，
                         # 前提是内部函数调用了外部函数的变量


r = greeting()                       # greeting 已执行完毕，返回内层函数 inner
print('闭包保存的变量 cell:', next(iter(r.__closure__)))   # 是一个 cell 对象
print('cell 里保存的值:', r.__closure__[0].cell_contents)  # 输出: 123
r()                                  # 调用内层函数，仍能读到 msg=123


# =====================================================================
# 补充示例一：闭包实现计数器（结合 nonlocal 修改自由变量）
# 这是"有状态函数"的经典写法，也是装饰器计时功能的底层基础
# =====================================================================
def make_counter(start=0):
    count = start               # 自由变量：被内层函数修改并保存

    def add(step=1):
        nonlocal count          # 声明修改外层函数的 count（不是新建局部变量）
        count += step
        return count

    return add                  # 返回内层函数，形成闭包


print('\n===== 补充示例一：闭包计数器 =====')
counter_a = make_counter()      # 创建一个计数器
counter_b = make_counter(100)   # 再创建一个独立的计数器（各自保存各自的 count）
print('counter_a():', counter_a())     # 1
print('counter_a():', counter_a())     # 2（状态被闭包保存并累加）
print('counter_b():', counter_b())     # 101（与 counter_a 互不影响）


# =====================================================================
# 补充示例二：闭包实现延迟计算
# 函数先定义好"计算方案"，需要结果时才真正执行
# =====================================================================
def lazy_power(x, n):
    """返回一个闭包：调用时才真正计算 x 的 n 次方"""
    def compute():
        return x ** n          # 捕获 x 和 n，调用时才算
    return compute


print('\n===== 补充示例二：延迟计算 =====')
pow_2_10 = lazy_power(2, 10)   # 此时并没有计算 2**10
print('调用前只是拿到一个函数对象:', pow_2_10)
print('真正调用时才计算结果:', pow_2_10())   # 输出: 1024


# =====================================================================
# 补充示例三：闭包陷阱 —— 循环中创建闭包共享同一个变量
# =====================================================================
print('\n===== 补充示例三：闭包陷阱 =====')

# 错误的写法：三个函数共享同一个循环变量 i
funcs_wrong = []
for i in range(3):
    funcs_wrong.append(lambda: i)   # 三个 lambda 引用的是同一个 i
# 循环结束后 i 停在 2，所以三个函数都返回 2
print('共享变量的结果:', [f() for f in funcs_wrong])   # 输出: [2, 2, 2]

# 正确的写法：用默认参数把当前值"绑定"进函数
funcs_right = []
for i in range(3):
    funcs_right.append(lambda i=i: i)   # 默认参数 i=i 把当前值复制了一份
print('用默认参数绑定的结果:', [f() for f in funcs_right])  # 输出: [0, 1, 2]
